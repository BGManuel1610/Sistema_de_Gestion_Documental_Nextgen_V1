import React, { useState } from 'react';
import { radicadoService } from '../services/api';
import { useLanguage } from '../contexts/LanguageContext';

export const RadicacionEntrada = () => {
  const { t } = useLanguage();
  const [remitente, setRemitente] = useState('');
  const [asunto, setAsunto] = useState('');
  const [tipoDoc, setTipoDoc] = useState('');
  const [sedeDestino, setSedeDestino] = useState('');
  const [errors, setErrors] = useState({});
  const [errorMessage, setErrorMessage] = useState('');
  const [successMessage, setSuccessMessage] = useState('');
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setErrorMessage('');
    setSuccessMessage('');

    // C.A.2 y C.A.3: Validar campos obligatorios
    const newErrors = {};
    if (!remitente.trim()) newErrors.remitente = true;
    if (!asunto.trim()) newErrors.asunto = true;
    if (!tipoDoc.trim()) newErrors.tipoDoc = true;
    if (!sedeDestino.trim()) newErrors.sedeDestino = true;

    if (Object.keys(newErrors).length > 0) {
      setErrors(newErrors);
      // C.A.3: Mensaje exacto de alerta
      setErrorMessage(t('radicacion.errorRequired'));
      return;
    }

    setErrors({});
    setLoading(true);

    try {
      // C.A.4: Inserción en backend
      const res = await radicadoService.crear({
        txt_remitente: remitente,
        txt_asunto: asunto,
        cmb_tipo_doc: tipoDoc,
        cmb_sede_destino: sedeDestino,
        dias_termino: 5
      });

      // C.A.5: Alerta verde con mensaje exacto conteniendo el código real
      setSuccessMessage(res.data.mensaje);
      // Limpiar campos
      setRemitente('');
      setAsunto('');
      setTipoDoc('');
      setSedeDestino('');
    } catch (err) {
      if (err.response && err.response.data && err.response.data.detail) {
        setErrorMessage(err.response.data.detail);
      } else {
        setErrorMessage(t('radicacion.errorGeneral'));
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <div id="frm_radicacion_entrada" className="card" style={{ maxWidth: '800px', margin: '0 auto' }}>
      <div className="card-header">
        <div>
          <h2 className="card-title">{t('radicacion.title')}</h2>
          <p style={{ color: 'var(--text-muted)', fontSize: '0.875rem' }}>
            {t('radicacion.module')}
          </p>
        </div>
      </div>

      {/* C.A.3: Alerta de error con mensaje exacto */}
      {errorMessage && (
        <div className="alert alert-red">
          <span>{errorMessage}</span>
          <button onClick={() => setErrorMessage('')} style={{ background: 'none', border: 'none', cursor: 'pointer', color: 'var(--color-red)' }}>✕</button>
        </div>
      )}

      {/* C.A.5: Alerta en verde con mensaje exacto */}
      {successMessage && (
        <div className="alert alert-green">
          <span>{successMessage}</span>
          <button onClick={() => setSuccessMessage('')} style={{ background: 'none', border: 'none', cursor: 'pointer', color: 'var(--color-green)' }}>✕</button>
        </div>
      )}

      <form onSubmit={handleSubmit}>
        {/* C.A.1: txt_codigo_radicado bloqueado mostrando AUTO-GENERADO */}
        <div className="form-group">
          <label className="form-label" htmlFor="txt_codigo_radicado">
            {t('radicacion.codeLabel')}
          </label>
          <input
            id="txt_codigo_radicado"
            type="text"
            className="form-input"
            value={t('radicacion.autoGenerated')}
            disabled
            readOnly
            style={{ fontWeight: 600, color: 'var(--primary)', backgroundColor: '#eff6ff' }}
          />
          <small style={{ color: 'var(--text-muted)', fontSize: '0.75rem' }}>
            El código secuencial (RAD-YYYY-XXXXX) se generará automáticamente de forma transaccional.
          </small>
        </div>

        {/* C.A.2: txt_remitente obligatorio */}
        <div className="form-group">
          <label className="form-label" htmlFor="txt_remitente">
            {t('radicacion.senderLabel')} *
          </label>
          <input
            id="txt_remitente"
            type="text"
            className={`form-input ${errors.remitente ? 'border-error' : ''}`}
            value={remitente}
            onChange={(e) => {
              setRemitente(e.target.value);
              if (errors.remitente) setErrors(prev => ({ ...prev, remitente: false }));
            }}
            placeholder={t('radicacion.senderPlaceholder')}
          />
        </div>

        {/* C.A.2: cmb_tipo_doc obligatorio */}
        <div className="form-group">
          <label className="form-label" htmlFor="cmb_tipo_doc">
            {t('radicacion.docTypeLabel')} *
          </label>
          <select
            id="cmb_tipo_doc"
            className={`form-select ${errors.tipoDoc ? 'border-error' : ''}`}
            value={tipoDoc}
            onChange={(e) => {
              setTipoDoc(e.target.value);
              if (errors.tipoDoc) setErrors(prev => ({ ...prev, tipoDoc: false }));
            }}
          >
            <option value="">{t('radicacion.selectDocType')}</option>
            <option value="Tutela">{t('radicacion.docTypeTutela')}</option>
            <option value="Derecho de Petición">{t('radicacion.docTypePetition')}</option>
            <option value="Oficio Judicial">{t('radicacion.docTypeJudicial')}</option>
            <option value="Factura">{t('radicacion.docTypeCommercial')}</option>
            <option value="Correspondencia General">{t('radicacion.docTypeOfficial')}</option>
          </select>
        </div>

        {/* C.A.2: cmb_sede_destino obligatorio */}
        <div className="form-group">
          <label className="form-label" htmlFor="cmb_sede_destino">
            {t('radicacion.targetBranchLabel')} *
          </label>
          <select
            id="cmb_sede_destino"
            className={`form-select ${errors.sedeDestino ? 'border-error' : ''}`}
            value={sedeDestino}
            onChange={(e) => {
              setSedeDestino(e.target.value);
              if (errors.sedeDestino) setErrors(prev => ({ ...prev, sedeDestino: false }));
            }}
          >
            <option value="">{t('radicacion.selectBranch')}</option>
            <option value="Bogotá">Bogotá</option>
            <option value="Medellín">Medellín</option>
            <option value="Cali">Cali</option>
          </select>
        </div>

        {/* C.A.2: txt_asunto obligatorio */}
        <div className="form-group">
          <label className="form-label" htmlFor="txt_asunto">
            {t('radicacion.subjectLabel')} *
          </label>
          <textarea
            id="txt_asunto"
            rows="4"
            className={`form-textarea ${errors.asunto ? 'border-error' : ''}`}
            value={asunto}
            onChange={(e) => {
              setAsunto(e.target.value);
              if (errors.asunto) setErrors(prev => ({ ...prev, asunto: false }));
            }}
            placeholder={t('radicacion.subjectPlaceholder')}
          />
        </div>

        <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: '1.5rem' }}>
          {/* C.A.3: btn_generar_radicado */}
          <button
            id="btn_generar_radicado"
            type="submit"
            className="btn btn-primary"
            disabled={loading}
            style={{ minWidth: '180px' }}
          >
            {loading ? t('radicacion.submitting') : t('radicacion.submitBtn')}
          </button>
        </div>
      </form>
    </div>
  );
};
